// Generates src/mealPhoto/genericFoodData.ts from the USDA FoodData Central
// "Survey (FNDDS)" CSV download. Usage:
//   bun scripts/generateGenericFoods.ts <extracted-csv-dir> <release-date> <retrieved-date>
// e.g. bun scripts/generateGenericFoods.ts ../../build/fndds/x/FoodData_Central_survey_food_csv_2024-10-31 2024-10-31 2026-11-27
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const [dir, releaseDate, retrievedDate] = process.argv.slice(2)
if (dir == null || releaseDate == null || retrievedDate == null) {
  throw new Error('usage: generateGenericFoods.ts <csv-dir> <release-date> <retrieved-date>')
}

// The FNDDS CSV's nutrient_id column holds legacy nutrient numbers, not FDC ids:
// energy 208 (FDC 1008), protein 203 (1003), carbs 205 (1005), fat 204 (1004),
// saturated fat 606 (1258), fiber 291 (1079), sugars 269 (2000), sodium 307 (1093), cholesterol 601 (1253).
const NUTRIENTS = [208, 203, 205, 204, 606, 291, 269, 307, 601] as const
const slot = new Map<number, number>(NUTRIENTS.map((id, index) => [id, index]))

// Baby food, formula, human milk and "as ingredient" rows are never plate components.
const EXCLUDED_CATEGORIES = new Set([9002, 9004, 9006, 9007, 9008, 9010, 9012, 9202, 9204, 9402, 9404, 9602, 9802, 9999])

function parseCsvLine(line: string): string[] {
  const fields: string[] = []
  let current = ''
  let quoted = false
  for (let i = 0; i < line.length; i += 1) {
    const ch = line[i]!
    if (quoted) {
      if (ch === '"' && line[i + 1] === '"') { current += '"'; i += 1 }
      else if (ch === '"') quoted = false
      else current += ch
    } else if (ch === '"') quoted = true
    else if (ch === ',') { fields.push(current); current = '' }
    else current += ch
  }
  fields.push(current)
  return fields
}

function lines(file: string): string[] {
  return readFileSync(join(dir, file), 'utf8').split(/\r?\n/).slice(1).filter((line) => line.length > 0)
}

const descriptions = new Map<number, string>()
for (const line of lines('food.csv')) {
  const [id, type, description] = parseCsvLine(line)
  if (type === 'survey_fndds_food') descriptions.set(Number(id), description!.trim())
}

const categories = new Map<number, number>()
for (const line of lines('survey_fndds_food.csv')) {
  const [id, , category] = parseCsvLine(line)
  categories.set(Number(id), Number(category))
}

const values = new Map<number, (number | null)[]>()
const nutrientLine = /^"\d+","(\d+)","(\d+)","([^"]*)"/
for (const line of lines('food_nutrient.csv')) {
  const match = nutrientLine.exec(line)
  if (match == null) continue
  const position = slot.get(Number(match[2]))
  if (position == null) continue
  const id = Number(match[1])
  if (!descriptions.has(id)) continue
  const row = values.get(id) ?? NUTRIENTS.map(() => null)
  const amount = Number(match[3])
  row[position] = match[3] === '' || !Number.isFinite(amount) ? null : Math.round(amount * 100) / 100
  values.set(id, row)
}

const rows: string[] = []
for (const [id, description] of [...descriptions].sort((a, b) => a[0] - b[0])) {
  const category = categories.get(id) ?? 9999
  const nutrition = values.get(id)
  // Energy and the three macros are required; a row without them cannot be a match.
  if (EXCLUDED_CATEGORIES.has(category) || nutrition == null) continue
  if (nutrition[0] == null || nutrition[1] == null || nutrition[2] == null || nutrition[3] == null) continue
  rows.push(`  [${id}, ${JSON.stringify(description)}, ${category}, ${nutrition.map((value) => value ?? 'null').join(', ')}],`)
}

const output = `// Generated by scripts/generateGenericFoods.ts. Do not edit by hand.
// Source: USDA FoodData Central, Survey (FNDDS) 2021-2023, download dated ${releaseDate} (public domain).
// Retrieved: ${retrievedDate}. Foods: ${rows.length}.
// Per 100 g. Row: [fdcId, description, WWEIA category, calories, protein, carbs, fat, saturatedFat, fiber, sugars, sodiumMg, cholesterolMg].
// null means FNDDS publishes no value; it is never estimated.
export type GenericFoodRow = readonly [
  fdcId: number,
  description: string,
  category: number,
  calories: number,
  protein: number,
  carbs: number,
  fat: number,
  saturatedFat: number | null,
  fiber: number | null,
  sugars: number | null,
  sodium: number | null,
  cholesterol: number | null,
]

export const genericFoodsDataset = { name: 'USDA FNDDS 2021-2023', releaseDate: '${releaseDate}', retrievedAt: '${retrievedDate}' } as const

export const genericFoodRows: readonly GenericFoodRow[] = [
${rows.join('\n')}
]
`
writeFileSync(join(import.meta.dir, '..', 'src', 'mealPhoto', 'genericFoodData.ts'), output)
console.log(`wrote ${rows.length} foods, ${output.length} bytes`)
